#!/usr/bin/env python3
"""Generate explicit P17-B fields from pinned firmware, never from plugin IDs.

The independent C oracle compiles the original declarations and menu tables;
it does not consume these generated files. No firmware file is modified.
"""
import argparse
import json
import pathlib
import re
from extract_modulation_contract import extract, enum_values, without_comments, AVR, ROOT


def generate():
    data = extract()  # Also verifies the clean original firmware revision.
    params = enum_values(AVR + 'Parameters.h')
    symbols = {}
    for name, number in params.items():
        if number < 228:
            symbols.setdefault(number, name)
    symbols[1] = 'PAR_OSC_WAVE_DRUM1'  # Source enum alias, not mod wheel.
    targets = {t['parameter_id']: t for t in data['targets'] + data['internal_only_parameters']}
    menu = (ROOT / (AVR + 'Menu/menu.c')).read_text()
    body = without_comments(menu).split('parameter_dtypes[NUM_PARAMS] = {', 1)[1].split('};', 1)[0]
    dtypes = [s.strip() for s in body.split(',') if s.strip()]
    assert len(dtypes) == 273
    owners = ['Drum1', 'Drum2', 'Drum3', 'Snare', 'Cymbal', 'HiHat', 'Global', 'Reserved']
    members = ['drum1', 'drum2', 'drum3', 'snare', 'cymbal', 'hiHat', 'global', 'reserved']
    rows = []
    for i in range(228):
        t = targets.get(i)
        owner = t['voice'] if t else None
        kind, maximum = 'Scalar', 127
        if i in (0, 5, 97, 98, 127):
            owner, kind, maximum = 7, 'Reserved', 255
        elif i == 114:
            owner = 6
        elif 149 <= i <= 154:
            owner, kind, maximum = i - 149, 'Selector', 204
        elif 161 <= i <= 166:
            owner, kind, maximum = i - 161, 'VoiceHint', 6
        elif 167 <= i <= 172:
            owner, kind, maximum = i - 167, 'Selector', 204
        if 'MENU_WAVEFORM' in dtypes[i]:
            # Upper bound depends on the device's SD sample inventory. Preserve
            # the source byte; >=6 is explicitly unsupported for native use.
            kind, maximum = 'OscillatorWave', 255
        elif 'MENU_' in dtypes[i]:
            menus = {'MENU_FILTER': 7, 'MENU_AUDIO_OUT': 5, 'MENU_SYNC_RATES': 11,
                     'MENU_LFO_WAVES': 7, 'MENU_RETRIGGER': 6, 'MENU_TRANS': 13}
            key = re.search(r'\((MENU_\w+)<<4\)', dtypes[i])[1]
            maximum = menus[key]
        elif dtypes[i] in ('DTYPE_MIX_FM', 'DTYPE_ON_OFF'):
            maximum = 1
        assert owner is not None, (i, symbols[i])
        field = symbols[i].removeprefix('PAR_').lower()
        rows.append(dict(id=i, symbol=symbols[i], owner=owners[owner], member=members[owner],
                         field=field, kind=kind, maximum=maximum, default=0,
                         dtype=dtypes[i], original_target=t['pointer'] if t else '',
                         native='Route' if kind == 'Selector' else 'Opaque' if kind in ('Reserved', 'VoiceHint') else 'Scalar'))
    notice = '// Generated by tools/verification/extract_kit_contract.py.\n// Original LXR 0.37 Copyright 2013 Julian Schmidt; see LICENSE-LXR.txt.\n'
    records = [notice]
    for owner in owners:
        records.append('struct ' + owner + 'Kit final {')
        for r in rows:
            if r['owner'] == owner:
                records.append('    ' + ('StoredSelector ' + r['field'] +
                    ' = StoredSelector::fromRaw(0);' if r['kind'] == 'Selector'
                    else 'std::uint8_t ' + r['field'] + ' = 0;') + ' // ID ' + str(r['id']))
        records.append('};\n')
    fields = [notice, '// K_BYTE / K_SELECTOR(id, symbol, member.path, owner, kind, max, native)']
    for r in rows:
        fields.append(('K_SELECTOR' if r['kind'] == 'Selector' else 'K_BYTE') +
                      f"({r['id']}, {r['symbol']}, {r['member']}.{r['field']}, {r['owner']}, {r['kind']}, {r['maximum']}, {r['native']})")
    return rows, '\n'.join(records).rstrip() + '\n', '\n'.join(fields) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--emit', action='store_true')
    ap.add_argument('--output', type=pathlib.Path, required=True)
    a = ap.parse_args()
    rows, records, fields = generate()
    for path, contents in [('dsp/KitRecords.inc', records), ('dsp/KitFields.inc', fields)]:
        p = ROOT / path
        if a.emit:
            p.write_text(contents, encoding='utf-8')
        else:
            assert p.read_text(encoding='utf-8') == contents, path + ' drift'
    a.output.mkdir(parents=True, exist_ok=True)
    (a.output / 'extracted_fields.json').write_text(json.dumps(rows, indent=2), encoding='utf-8')
    print('228 fields, six synthesis owners; generated contracts verified')


if __name__ == '__main__':
    main()
